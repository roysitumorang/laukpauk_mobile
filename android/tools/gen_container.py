#!/usr/bin/env python3
"""Regenerates app/src/main/java/id/laukpauk/di/AppContainer.java.

Every concrete class `public class XxxRepository extends BaseRepository` in data/repository gets one
singleton field `xxxRepository`. Its constructor must start with the shared RepositoryDeps and may then
take other repositories (`public CartRepository(RepositoryDeps deps, DeliveryRepository delivery)`);
they are built in dependency order, and a cycle is an error. Run it after adding or removing a
repository (CI fails if the committed file is out of date):

    python3 android/tools/gen_container.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "app", "src", "main", "java", "id", "laukpauk")
REPO_DIR = os.path.join(SRC, "data", "repository")
OUT = os.path.join(SRC, "di", "AppContainer.java")


def field(cls):
    m = re.match(r"^([A-Z]+)(?=[A-Z][a-z])|^([A-Z])", cls)
    lead = m.group(0)
    return lead.lower() + cls[len(lead):]


repos, params = [], {}
for f in sorted(os.listdir(REPO_DIR)):
    if not f.endswith(".java"):
        continue
    cls = f[:-5]
    text = open(os.path.join(REPO_DIR, f), encoding="utf-8").read()
    if re.search(r"public\s+(final\s+)?class\s+%s\s+extends\s+BaseRepository\b" % cls, text):
        repos.append(cls)
        m = re.search(r"public\s+%s\s*\(([^)]*)\)" % cls, text)
        types = [p.strip().split()[-2] for p in m.group(1).split(",") if p.strip()] if m else ["RepositoryDeps"]
        if not types or types[0] != "RepositoryDeps":
            raise SystemExit("%s: the constructor must start with RepositoryDeps" % cls)
        params[cls] = types[1:]

# constructor injection between repositories: build in dependency order
order, state = [], {}


def visit(r, path):
    if state.get(r) == 2:
        return
    if state.get(r) == 1:
        raise SystemExit("repository dependency cycle: " + " -> ".join(path + [r]))
    state[r] = 1
    for d in params[r]:
        if d not in params:
            raise SystemExit("%s depends on %s, which is not a repository" % (r, d))
        visit(d, path + [r])
    state[r] = 2
    order.append(r)


for r in repos:
    visit(r, [])

lines = [
    "package id.laukpauk.di;",
    "",
    "// GENERATED by android/tools/gen_container.py - do not edit by hand; re-run the script instead.",
    "",
    "import android.app.Application;",
    "import android.content.Context;",
    "",
    "import id.laukpauk.LaukpaukApp;",
    "import id.laukpauk.data.local.SessionStore;",
    "import id.laukpauk.data.local.Prefs;",
    "import id.laukpauk.data.remote.ApiClient;",
    "import id.laukpauk.data.repository.RepositoryDeps;",
]
lines += ["import id.laukpauk.data.repository.%s;" % r for r in repos]
lines += [
    "import id.laukpauk.util.AppExecutors;",
    "",
    "/**",
    " * Composition root (manual dependency injection). Created once in {@link LaukpaukApp#onCreate()}.",
    " *",
    " * Holds the app's singletons: infrastructure (preferences, session, HTTP client, executors) and one",
    " * instance of every repository. ViewModels receive the repositories they need through their",
    " * constructors, via {@link ViewModelFactory}; Fragments get the container with {@link #from(Context)}.",
    " */",
    "public final class AppContainer {",
    "",
    "    public final Application application;",
    "    public final Prefs prefs;",
    "    public final SessionStore session;",
    "    public final ApiClient apiClient;",
    "    public final AppExecutors executors;",
    "    private final RepositoryDeps repositoryDeps;",
    "",
]
lines += ["    public final %s %s;" % (r, field(r)) for r in repos]
lines += [
    "",
    "    public AppContainer(Application application) {",
    "        this.application = application;",
    "        this.prefs = new Prefs(application);",
    "        this.session = new SessionStore(application, prefs);",
    "        this.apiClient = new ApiClient(session);",
    "        this.executors = new AppExecutors();",
    "        this.repositoryDeps = new RepositoryDeps(application, apiClient, session, prefs, executors);",
]
lines += ["        this.%s = new %s(%s);" % (field(r), r, ", ".join(["repositoryDeps"] + ["this." + field(d) for d in params[r]])) for r in order]
lines += [
    "    }",
    "",
    "    /** The container of the running app, from any Context (Activity, Fragment's context, View, Application). */",
    "    public static AppContainer from(Context context) {",
    "        return ((LaukpaukApp) context.getApplicationContext()).appContainer();",
    "    }",
    "}",
    "",
]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
new = "\n".join(lines)
old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
if new != old:
    open(OUT, "w", encoding="utf-8").write(new)
print("AppContainer: %d repositories" % len(repos))
